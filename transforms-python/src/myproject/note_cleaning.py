"""
note_cleaning.py -- deterministic boilerplate stripper for clinical notes (NO LLM).

Instead of extracting only the A&P (text_sections.extract_excerpt), this KEEPS the
full clinical narrative and REMOVES known low-value boilerplate sections (Review of
Systems, Physical Exam, Labs, Medications, Family/Social/Past-Medical History,
Allergies, performance-status scales, consent, palliative symptom scales) plus
copy-paste footer/signature blocks.

The Past Surgical History (PSH) block is copy-pasted VERBATIM across a patient's
notes (an EHR-autogenerated cumulative list, like the Cancer Treatment History), so
it is pulled OUT to a separate field to be de-duplicated to ONE canonical copy per
patient rather than repeated in every note. NOTE: this release extracts the PSH block
(strip_boilerplate -> psh_block) but ships no downstream consumer for it; the per-patient
dedup stage is not included.

Design (robust to inconsistent EHR formatting):
  1. normalize   -- CRLF->LF, tabs->space, runs of 2+ spaces -> newline
  2. segment     -- split at EVERY recognized header (KEEP | REMOVE | PSH registry)
  3. classify    -- drop REMOVE; keep KEEP + UNKNOWN (conservative); PSH -> own field
  4. struct wipe -- remove residual lab / vitals / ROS-PE body-system / med lines
  5. footer wipe -- remove signature / address / dictation footer lines
  6. empty check -- < MIN_KEEP_CHARS remaining -> flag stripped_empty

Everything is deterministic, dependency-free, and unit-testable without Spark.
"""
